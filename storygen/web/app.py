"""FastAPI web app for the Interactive Story Generator: serves the front end in static/ and the JSON API under /api.

The story is generated in the browser by static/story_engine.js, a port of storygen that gives the same story for the
same seed (node-tested against tests/fixtures/stories.json). The API supplies the generator's content (/spec), Python
stories for checking the port (/samples, /story) and project counts (/info).

Run with `python run_web.py` (http://127.0.0.1:8138, local only). `scripts/build_static.py` exports every path in
STATIC_ENDPOINTS to JSON for the GitHub Pages site, so keep that list in step with the GET routes below.
"""
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles

from storygen.web import story_api

STATIC = Path(__file__).resolve().parent / "static"

app = FastAPI(title="Interactive Story Generator")
app.mount("/static", StaticFiles(directory=STATIC), name="static")


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(STATIC / "index.html")


@app.get("/api/info")
def info():
    """Counts for the home page, read from the generator's content."""
    s = story_api.spec()
    return {
        "title": "Interactive Story Generator",
        "locations": len(s["locations"]), "characters": len(s["characters"]), "items": len(s["items"]),
        "templates": sum(len(v) for v in s["templates"].values()), "phases": len(s["templates"]),
        "themes": len(s["themes"]), "emotions": len(s["emotions"]), "max_branches": s["max_branches"],
    }


@app.get("/api/spec")
def spec():
    """Plot templates, themes, emotions and the world lists the generator uses."""
    return story_api.spec()


@app.get("/api/samples")
def samples():
    """Python stories for the sample seeds (the static site checks the JS engine against these)."""
    return {"seeds": story_api.SAMPLE_SEEDS, "branches": story_api.SAMPLE_BRANCHES, "stories": story_api.samples()}


@app.get("/api/story/{seed}")
def story(seed: int, branches: int = 3):
    """One story generated by the Python package (local app only)."""
    try:
        return story_api.story(seed, branches)
    except ValueError as e:
        raise HTTPException(422, str(e)) from e


# GET paths (without the /api prefix) written to the static site as api/<path>.json.
STATIC_ENDPOINTS = ["/info", "/spec", "/samples"]
