// Home: hero, counts read from the generator, today's sample story and the doors to the pages.
import { route, app, api, esc } from './core.js';
import { pickStory } from './store.js';

route('home', async () => {
  const [info, { story, saved }] = await Promise.all([api('/info'), pickStory({})]);
  const q = `seed=${story.seed}&branches=${story.branches}`;
  app().innerHTML = `<section class="hero"><p class="kicker">Procedural narrative · branching paths</p>
    <h1 class="glow">Interactive Story Generator</h1>
    <p class="lead">A procedural narrative generator: it builds a small world of places, characters and objects,
      gives every pair of characters a relationship, and grows a branching story from an introduction through
      development and climax to several endings. Here it runs in your browser and gives the same story as the Python
      package for the same seed.</p>
    <a class="btn" href="#/play?${q}">${saved ? 'Continue your story' : 'Play a story'}</a>
    <a class="btn alt" href="#/play?seed=${Math.floor(Math.random() * 1e6)}&branches=3">Random seed</a></section>
    <div class="tiles"><div class="tile"><b>${info.locations}</b><span>places</span></div>
      <div class="tile"><b>${info.characters}</b><span>characters</span></div><div class="tile"><b>${info.items}</b><span>objects</span></div>
      <div class="tile"><b>${info.templates}</b><span>plot templates in ${info.phases} phases</span></div>
      <div class="tile"><b>${info.themes}</b><span>themes</span></div><div class="tile"><b>1-${info.max_branches}</b><span>branches</span></div></div>
    <div class="panel"><p class="kicker">${saved ? 'Your saved story' : 'Sample story'} · seed ${story.seed}</p>
      <h2 style="margin-top:0">${esc(story.title)}</h2><p class="scene">${esc(story.events[0].text)}...</p></div>
    <div class="grid">
      <a class="card door" href="#/play?${q}"><b>Play</b><small>gamebook reader</small><span>Choose a path at the crossroads,
        follow it to its ending, come back for the others. Progress is saved in this browser.</span></a>
      <a class="card door" href="#/world?${q}"><b>World</b><small>relationship graph</small><span>The characters'
        relationship strengths as a graph, and which events mention each place, character and object.</span></a>
      <a class="card door" href="#/story?${q}"><b>Script</b><small>every branch at once</small><span>The full story as the
        command-line tool prints it, with a download of story_data.json.</span></a>
      <a class="card door" href="#/verify"><b>Check</b><small>JS vs Python</small><span>The browser generator compared with
        stories generated by the Python package.</span></a>
    </div>`;
});
